"""Step 6: write the LAYERS / GROUPS config into index.html (between the CONFIG markers) from the generated layers,
including where each element hides behind the boy (nearest point at least 15 units inside boy.png's silhouette)."""
import json, re, numpy as np, cv2
from PIL import Image
ROOT = __file__.rsplit('/tools/', 1)[0]
P = json.load(open(f'{ROOT}/tools/parts.json')); HL = json.load(open(f'{ROOT}/tools/hair_layers.json')); E = json.load(open(f'{ROOT}/tools/element_layers.json'))
a = np.asarray(Image.open(f'{ROOT}/assets/layers/boy.png'))[..., 3] / 255
inner = cv2.erode((a > 0.95).astype(np.uint8), np.ones((31, 31), np.uint8)); ys, xs = np.where(inner)
def L(p, extra=''): return "{ file:'%s', x:%d, y:%d, w:%d, h:%d%s }" % (p['file'], p['x'], p['y'], p['w'], p['h'], extra)
lines = ["const LAYERS = {",
 "  BACKGROUND: { file:'assets/layers/background.jpg', x:-24, y:-24, w:1246, h:848 },",
 "  BOY:        { file:'assets/layers/boy.png', x:0, y:0, w:1198, h:800 },"]
for n, org in [('hair_top', '50% 88%'), ('hair_left', '85% 4%'), ('hair_right', '15% 4%')]:
    v = HL[n]; lines.append("  %s: { file:'assets/layers/%s.png', x:%d, y:%d, w:%d, h:%d, origin:'%s' }," % (n.upper(), n, v['x'], v['y'], v['w'], v['h'], org))
lines += ["  BULB:       " + L(P['bulb']) + ",",
          "  BULB_RAYS: [" + ", ".join(L(r, ", origin:'%s%% %s%%'" % (r['origin'][0], r['origin'][1])) for r in P['bulb_rays']) + "],",
          "  CHART_CARD: " + L(P['chart']['card'], ", tilt:-6.4") + ",",
          "  CHART_BARS: [" + ", ".join(L(r) for r in P['chart']['marks']) + "],",
          "  LIST_CARD:  " + L(P['list']['card'], ", tilt:7.5") + ",",
          "  LIST_LINES: [" + ", ".join(L(r) for r in P['list']['marks']) + "],",
          "  PLANE:      " + L(P['plane']) + ",",
          "  PLANE_TRAIL:" + L(P['plane_trail']) + ",",
          "  DOTS: [" + ", ".join(L(r) for r in P['dots']) + "],",
          "  CIRCLE:     " + L(P['circle']) + ",", "};",
          "// element groups: box on the canvas, where each hides behind the boy (from boy.png's alpha), idle float rhythm",
          "const GROUPS = {"]
rhythm = {'dots': ('3.8s', '-1.1s'), 'circle': ('4.6s', '-2.4s'), 'bulb': ('3.4s', '0s'), 'chart': ('4.0s', '-.8s'), 'list': ('4.6s', '-1.7s'), 'plane': ('3.8s', '-.4s')}
for n in ['dots', 'circle', 'bulb', 'chart', 'list', 'plane']:
    e = E[n]; cx, cy = e['x'] + e['w'] / 2, e['y'] + e['h'] / 2
    k = np.argmin((xs - cx) ** 2 + (ys - cy) ** 2); dx, dy = xs[k] - cx, ys[k] - cy; d = np.hypot(dx, dy)
    hx, hy = dx + dx / d * 20, dy + dy / d * 20
    lines.append("  %-7s { x:%d, y:%d, w:%d, h:%d, hideDx:%.1f, hideDy:%.1f, dur:'%s', delay:'%s' }," % (n + ':', e['x'], e['y'], e['w'], e['h'], hx, hy, *rhythm[n]))
lines.append("};")
s = open(f'{ROOT}/index.html').read()
s = re.sub(r"/\* CONFIG:START.*?\*/.*?/\* CONFIG:END \*/", lambda m: "/* CONFIG:START (generated by tools/build_config.py) */\n" + "\n".join(lines) + "\n/* CONFIG:END */", s, flags=re.S)
open(f'{ROOT}/index.html', 'w').write(s)
print("\n".join(lines))
